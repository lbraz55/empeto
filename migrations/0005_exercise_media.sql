-- EMPETO — biblioteca visual (documento de evolução v1.1, 5.1/5.2).
-- illustration: id estável de uma ilustração própria em assets/exercises ('' = escolher pelo padrão de movimento).
-- video_url: link externo opcional informado pelo usuário (https). Nada é baixado pelo app.
ALTER TABLE exercise ADD COLUMN illustration TEXT NOT NULL DEFAULT '';
ALTER TABLE exercise ADD COLUMN video_url TEXT NOT NULL DEFAULT '';

UPDATE exercise SET illustration = CASE name
  WHEN 'Supino reto com barra' THEN 'bench-press'
  WHEN 'Supino reto com halteres' THEN 'bench-press'
  WHEN 'Supino inclinado com barra' THEN 'bench-press'
  WHEN 'Supino inclinado com halteres' THEN 'bench-press'
  WHEN 'Supino na máquina' THEN 'bench-press'
  WHEN 'Crucifixo com halteres' THEN 'fly'
  WHEN 'Crucifixo na máquina (peck deck)' THEN 'fly'
  WHEN 'Crossover no cabo' THEN 'fly'
  WHEN 'Flexão de braços' THEN 'push-up'
  WHEN 'Barra fixa' THEN 'pull-up'
  WHEN 'Puxada frontal no pulley' THEN 'pulldown'
  WHEN 'Puxada com triângulo' THEN 'pulldown'
  WHEN 'Remada curvada com barra' THEN 'row'
  WHEN 'Remada unilateral com halter' THEN 'row'
  WHEN 'Remada baixa no cabo' THEN 'row'
  WHEN 'Remada na máquina' THEN 'row'
  WHEN 'Pulldown com braços estendidos' THEN 'pulldown'
  WHEN 'Desenvolvimento com barra' THEN 'overhead-press'
  WHEN 'Desenvolvimento com halteres' THEN 'overhead-press'
  WHEN 'Desenvolvimento na máquina' THEN 'overhead-press'
  WHEN 'Elevação lateral com halteres' THEN 'lateral-raise'
  WHEN 'Elevação lateral no cabo' THEN 'lateral-raise'
  WHEN 'Crucifixo invertido' THEN 'lateral-raise'
  WHEN 'Face pull' THEN 'row'
  WHEN 'Rosca direta com barra' THEN 'curl'
  WHEN 'Rosca alternada com halteres' THEN 'curl'
  WHEN 'Rosca martelo' THEN 'curl'
  WHEN 'Rosca no cabo' THEN 'curl'
  WHEN 'Tríceps pulley' THEN 'triceps-extension'
  WHEN 'Tríceps francês com halter' THEN 'triceps-extension'
  WHEN 'Tríceps testa com barra' THEN 'triceps-extension'
  WHEN 'Mergulho nas paralelas' THEN 'dip'
  WHEN 'Agachamento livre com barra' THEN 'squat'
  WHEN 'Agachamento no Smith' THEN 'squat'
  WHEN 'Agachamento goblet' THEN 'squat'
  WHEN 'Leg press 45°' THEN 'leg-press'
  WHEN 'Agachamento hack' THEN 'squat'
  WHEN 'Cadeira extensora' THEN 'leg-extension'
  WHEN 'Afundo com halteres' THEN 'lunge'
  WHEN 'Agachamento búlgaro' THEN 'lunge'
  WHEN 'Levantamento terra' THEN 'deadlift'
  WHEN 'Levantamento terra romeno' THEN 'deadlift'
  WHEN 'Stiff com halteres' THEN 'deadlift'
  WHEN 'Mesa flexora' THEN 'leg-curl'
  WHEN 'Cadeira flexora' THEN 'leg-curl'
  WHEN 'Elevação pélvica com barra' THEN 'hip-thrust'
  WHEN 'Cadeira abdutora' THEN 'hip-abduction'
  WHEN 'Glúteo no cabo' THEN 'hip-thrust'
  WHEN 'Panturrilha em pé' THEN 'calf-raise'
  WHEN 'Panturrilha sentado' THEN 'calf-raise'
  WHEN 'Prancha' THEN 'plank'
  WHEN 'Abdominal supra' THEN 'crunch'
  WHEN 'Abdominal no cabo' THEN 'crunch'
  WHEN 'Elevação de pernas' THEN 'leg-raise'
  WHEN 'Esteira' THEN 'cardio-run'
  WHEN 'Bicicleta ergométrica' THEN 'cardio-bike'
  ELSE '' END
WHERE is_custom = 0;
